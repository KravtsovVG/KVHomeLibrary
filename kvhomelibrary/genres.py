def normalize_genre(code: str) -> str:
    """Привести код/название категории к каноническому коду."""
    value = (code or "").strip()
    if not value:
        return "unknown"

    key = value.casefold()
    if key in GENRE_ALIASES:
        return GENRE_ALIASES[key]
    if key in GENRE_NAMES:
        return key

    underscored = key.replace("-", "_").replace(" ", "_")
    if underscored in GENRE_ALIASES:
        return GENRE_ALIASES[underscored]
    if underscored in GENRE_NAMES:
        return underscored

    return value


def genre_name(code: str) -> str:
    """Русское название жанра по коду FB2 (или сам код)."""
    canonical = normalize_genre(code)
    return GENRE_NAMES.get(canonical, code.strip() if code else "Без категории")


def genre_synonyms(code: str) -> tuple[str, ...]:
    """Русские синонимы категории без повторения основного названия."""
    canonical = normalize_genre(code)
    primary = genre_name(code).casefold()
    result: list[str] = []
    seen: set[str] = {primary}
    for synonym in GENRE_SYNONYMS.get(canonical, ()):
        key = synonym.casefold()
        if key and key not in seen:
            seen.add(key)
            result.append(synonym)
    return tuple(result)

